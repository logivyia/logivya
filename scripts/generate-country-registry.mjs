import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const sourcePath = path.join(root, "shared", "country-registry.json");
const targetPath = path.join(root, "apps", "mobile", "src", "generated", "country-registry.ts");
const source = JSON.parse(await fs.readFile(sourcePath, "utf8"));

if (!Number.isInteger(source.version) || !Array.isArray(source.countries) || source.countries.length === 0) {
  throw new Error("COUNTRY_REGISTRY_INVALID");
}

const seenIso = new Set();
for (const country of source.countries) {
  if (!/^[A-Z]{2}$/.test(country.countryIso) || !/^\+\d{1,3}$/.test(country.callingCode)) {
    throw new Error(`COUNTRY_REGISTRY_INVALID_ENTRY:${country.countryIso ?? "unknown"}`);
  }
  if (seenIso.has(country.countryIso)) throw new Error(`COUNTRY_REGISTRY_DUPLICATE_ISO:${country.countryIso}`);
  seenIso.add(country.countryIso);
}

const output = `/* This file is generated by scripts/generate-country-registry.mjs. */\n` +
  `export const countryRegistryVersion = ${JSON.stringify(source.version)} as const;\n` +
  `export const countryRegistry = ${JSON.stringify(source.countries, null, 2)} as const;\n` +
  `export type MobileCountryRegistryEntry = (typeof countryRegistry)[number];\n`;

await fs.mkdir(path.dirname(targetPath), { recursive: true });
await fs.writeFile(targetPath, output, "utf8");
console.log(`Generated ${path.relative(root, targetPath)} from ${path.relative(root, sourcePath)}`);
