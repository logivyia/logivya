import { writeFileSync } from "node:fs";
import { marketplaceCountries } from "../../shared/marketplace-filters.ts";

// Generate with Node's ICU data; native Hermes does not implement DisplayNames.
const locales = ["tr", "en", "ar", "ro", "ru", "az", "tk", "de", "bg", "el", "sr", "uz"];
const data = Object.fromEntries(locales.map(locale => {
  const names = new Intl.DisplayNames([locale === "sr" ? "sr-Latn" : locale], { type: "region" });
  return [locale, Object.fromEntries(marketplaceCountries.map(([code, fallback]) => [code, names.of(code) || fallback]))];
}));
writeFileSync(new URL("../../apps/mobile/src/features/freight/country-labels.ts", import.meta.url),
  "// Generated by scripts/release/generate-mobile-country-labels.mjs; no native Intl.DisplayNames dependency.\n" +
  "const countryLabels: Record<string, Record<string, string>> = " + JSON.stringify(data, null, 2) + ";\n" +
  "export function mobileCountryLabel(code: string, locale: string, fallback = code): string { return countryLabels[locale]?.[code] ?? countryLabels.en?.[code] ?? fallback; }\n");
